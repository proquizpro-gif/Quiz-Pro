/* Runs before every build (npm prebuild / predev).

   1. Seals the built-in bank: public/qaapf-bank.<hash>.sealed.json is
      the bank encrypted with the passphrase in bank-secret.txt. Only
      staff can obtain the passphrase (STEP7), so the published site no
      longer contains readable questions, keys or explanations.
   2. Writes src/lib/generated/qaapf-public.js: the bank version and,
      for each question, a hash of its text with its domain, unit and
      level — what the exam screen and a student's own profile need,
      and nothing a student could use to find an answer.

   Fails the build if STEP7 was generated with a different passphrase. */
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync, mkdirSync } from "fs";
import { createHash } from "crypto";
import { seal, unseal, stemHash, normStem } from "../src/lib/seal.js";
import { QAAPF_QUESTIONS as Q, QAAPF_LEGACY as L, QAAPF_BANK_VERSION, QAAPF_BANK_DATE } from "../src/lib/qaapf-bank.js";

const root = new URL("..", import.meta.url).pathname;
const secretFile = root + "bank-secret.txt";
if (!existsSync(secretFile)) { console.error("bank-secret.txt is missing: the built-in bank cannot be sealed. Restore it from the release package."); process.exit(1); }
const secret = readFileSync(secretFile, "utf8").trim();
if (secret.length < 24) { console.error("bank-secret.txt is too short."); process.exit(1); }
const step7 = readdirSync(root).find(f => /^STEP7.*\.sql$/.test(f));
if (step7 && !readFileSync(root + step7, "utf8").includes(secret)) {
  console.error(`${step7} was made with a different passphrase from bank-secret.txt. Use the pair from the same release.`); process.exit(1);
}

// 1. sealed bank
const payload = JSON.stringify({ version: QAAPF_BANK_VERSION, date: QAAPF_BANK_DATE, questions: Q, legacy: L });
const hash = createHash("sha256").update(payload).digest("hex").slice(0, 10);
const file = `qaapf-bank.${hash}.sealed.json`;
mkdirSync(root + "public", { recursive: true });
for (const f of readdirSync(root + "public")) if (/^qaapf-bank\..*\.sealed\.json$/.test(f) && f !== file) unlinkSync(root + "public/" + f);
if (!existsSync(root + "public/" + file)) {
  const env = await seal(payload, secret);
  if (await unseal(env, secret) !== payload) { console.error("Sealed bank failed its round trip."); process.exit(1); }
  writeFileSync(root + "public/" + file, JSON.stringify(env));
}

// 2. public level list
const meta = {};
const put = (stem, row) => {
  const h = stemHash(normStem(stem));
  if (meta[h] && meta[h] !== row) { console.error(`Two different questions share the fingerprint ${h}; reword one: ${stem}`); process.exit(1); }
  meta[h] = row;
};
const row = (id, d, u, t, lv, cat) => [id, d, u, t, lv, cat ? 1 : 0].join("|");
const byId = new Map(Q.map(q => [q.id, q]));
for (const q of Q) put(q.q, row(q.id, q.d, q.u, q.t, q.lv, q.k === "cat"));
for (const x of L) { const n = x.next ? byId.get(x.next) : null; if (!meta[stemHash(normStem(x.q))]) put(x.q, n ? row(n.id, n.d, n.u, n.t, n.lv, n.k === "cat") : row("", x.d, x.u, x.t, x.lv, false)); }
mkdirSync(root + "src/lib/generated", { recursive: true });
writeFileSync(root + "src/lib/generated/qaapf-public.js",
`/* Generated by scripts/build-bank.mjs — do not edit. No question text,
   options or answers: a text fingerprint → "id|domain|unit|tag|level|cat". */
export const PUBLIC_VERSION = ${JSON.stringify(QAAPF_BANK_VERSION)};
export const PUBLIC_DATE = ${JSON.stringify(QAAPF_BANK_DATE)};
export const SEALED_BANK_FILE = ${JSON.stringify(file)};
export const PUBLIC_META = ${JSON.stringify(meta)};
`);
console.log(`Bank v${QAAPF_BANK_VERSION} sealed as public/${file}; public level list has ${Object.keys(meta).length} entries.`);
